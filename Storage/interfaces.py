from __future__ import annotations

from typing import Any, Protocol

from Storage.models import (
    AccessDecision, AdminCommand, AdminResult, ModerationEvent, ModerationOutcome,
    ActivationResult, Page, UserProfile, UserRecord, UserSelection,
)


class UserRepository(Protocol):
    async def observe(self, profile: UserProfile, timestamp: str) -> UserRecord: ...
    async def get(self, user_id: int) -> UserRecord | None: ...
    async def access(self, user_id: int, timestamp: str, *, requires_grok: bool = False, requires_premium: bool = False) -> AccessDecision: ...
    async def authorize(self, user_id: int, timestamp: str) -> AccessDecision: ...
    async def selection(self, chat_id: int, user_id: int) -> UserSelection: ...
    async def select_model(self, chat_id: int, user_id: int,
                           selection: UserSelection, timestamp: str, *, requires_grok: bool = False, requires_premium: bool = False) -> bool: ...
    async def available_models(self, user_id: int, timestamp: str, provider: str) -> tuple: ...


class ModerationRepository(Protocol):
    async def record(self, event: ModerationEvent) -> int: ...
    async def record_refusal(self, event: ModerationEvent) -> int: ...
    async def policy_state(self) -> dict: ...
    async def save_safety_evaluation(self, record: dict) -> int: ...
    async def confirm(self, event: ModerationEvent) -> ModerationOutcome: ...
    async def active_warnings(self, user_id: int) -> int: ...
    async def block_for_user(self, user_id: int, sanction_id: int | None = None) -> dict: ...
    async def create_appeal(self, *, user_id: int, sanction_id: int, explanation: str,
                            timestamp: str, admin_ids: tuple[int, ...]) -> dict: ...
    async def appeal_for_user(self, user_id: int, appeal_id: int) -> dict: ...
    async def list_for_user(self, user_id: int, limit: int) -> list[dict[str, Any]]: ...


class UsageRepository(Protocol):
    async def start_request(self, *, request_id: str, user_id: int, timestamp: str,
                            model: str, provider: str, requires_grok: bool = False, requires_premium: bool = False) -> AccessDecision: ...
    async def start_attempt(self, *, attempt_id: str, request_id: str,
                            user_id: int, timestamp: str, model: str,
                            provider: str, requires_grok: bool = False, purpose: str = "product",
                            requires_premium: bool = False, is_main_inference: bool = True) -> AccessDecision: ...
    async def record_input_moderation(self, *, request_id: str, status: str, timestamp: str,
                                     source: str | None = None, model: str | None = None,
                                     provider: str | None = None, policy: str | None = None, safety_action: str | None = None) -> None: ...
    async def finish_attempt(self, *, attempt_id: str, status: str, latency_ms: int,
                             input_tokens: int | None, output_tokens: int | None,
                             total_tokens: int | None, error_type: str | None,
                             error_code: str | None, counts_toward_limit: bool = True) -> None: ...
    async def finish_request(self, *, request_id: str, status: str, timestamp: str,
                             latency_ms: int, error_type: str | None = None,
                             error_code: str | None = None, moderation_blocked: bool = False) -> None: ...
    async def recover_interrupted(self, timestamp: str) -> int: ...


class AdminRepository(Protocol):
    # Each command is one transaction, including its audit and moderation links.
    async def apply(self, command: AdminCommand) -> AdminResult: ...
    async def user_overview(self, user_id: int, timestamp: str) -> dict[str, Any]: ...
    async def audit_for_user(self, user_id: int, limit: int) -> list[dict[str, Any]]: ...
    async def counts(self) -> dict[str, int]: ...
    async def page(self, resource: str, page: int = 0, *, user_id: int | None = None,
                   filter_value: str = "all", search: str = "", page_size: int = 8) -> Page: ...
    async def detail(self, resource: str, resource_id: int) -> dict: ...
    async def dashboard(self, timestamp: str) -> dict: ...
    async def safety_summary(self, timestamp: str, fingerprint: str) -> dict: ...


class AccountRepository(Protocol):
    async def snapshot(self, user_id: int, timestamp: str) -> dict: ...
    async def apply(self, user_id: int, timestamp: str, admin_ids: tuple[int, ...]) -> dict: ...
    async def redeem(self, *, user_id: int, purpose: str, matches: bool, configured: bool,
                     timestamp: str, max_attempts: int, window_seconds: int, cooldown_seconds: int) -> ActivationResult: ...


class NotificationRepository(Protocol):
    async def pending(self, timestamp: str) -> list[dict]: ...
    async def finish(self, notification_id: int, *, timestamp: str, status: str,
                     next_attempt_at: str, error_code: str | None) -> None: ...


class StorageBackend(Protocol):
    users: UserRepository
    moderation: ModerationRepository
    usage: UsageRepository
    admins: AdminRepository
    accounts: AccountRepository
    notifications: NotificationRepository

    async def open(self) -> None: ...
    async def acquire_runtime(self) -> None: ...
    async def close(self) -> None: ...
    async def purge(self, *, usage_before: str, moderation_before: str,
                    audit_before: str, batch_size: int = 500) -> dict[str, int]: ...
